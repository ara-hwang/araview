#!/usr/bin/env bash
# Linux x64 개발용 libheif를 매니페스트의 고정 버전으로 설치한다.
# 실행 후 source target/linux-native-env.sh로 현재 셸에 빌드 환경을 적용한다.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [[ "$(uname -s)" != Linux || "$(uname -m)" != x86_64 ]]; then
  echo "이 스크립트는 Linux x64용입니다." >&2
  exit 1
fi

vcpkg_root="${VCPKG_ROOT:-${VCPKG_INSTALLATION_ROOT:-$HOME/vcpkg}}"
if [[ ! -x "$vcpkg_root/vcpkg" ]]; then
  echo "vcpkg를 먼저 설치하고 VCPKG_ROOT를 지정하세요: $vcpkg_root" >&2
  exit 1
fi
vcpkg_root="$(cd "$vcpkg_root" && pwd)"

# 버전 pin은 이전 port의 git tree를 읽는다. 얕은 복제에는 그 tree가 없다.
if [[ "$(git -C "$vcpkg_root" rev-parse --is-shallow-repository)" == true ]]; then
  git -C "$vcpkg_root" fetch --unshallow origin
fi

(
  cd "$root"
  "$vcpkg_root/vcpkg" install --triplet x64-linux \
    --x-install-root="$vcpkg_root/installed" --disable-metrics
)

export VCPKG_ROOT="$vcpkg_root"
export VCPKG_DEFAULT_TRIPLET=x64-linux
export PKG_CONFIG_PATH="$vcpkg_root/installed/x64-linux/lib/pkgconfig${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}"
export PKG_CONFIG_ALL_STATIC=1
pkg-config --atleast-version=1.21 libheif
pkg-config --static --libs libheif

# 개인 설치 경로는 추적하지 않고, 로그인 셸이 아닌 터미널에서도 명시적으로 적용한다.
mkdir -p "$root/target"
env_file="$root/target/linux-native-env.sh"
{
  printf '# Generated by scripts/setup-linux-native.sh. Source this file in Bash.\n'
  printf 'export VCPKG_ROOT=%q\n' "$VCPKG_ROOT"
  printf 'export VCPKG_DEFAULT_TRIPLET=x64-linux\n'
  printf 'export PKG_CONFIG_PATH=%q\n' "$PKG_CONFIG_PATH"
  printf 'export PKG_CONFIG_ALL_STATIC=1\n'
} > "$env_file"

printf 'libheif %s 준비 완료. 현재 셸에 적용:\n' "$(pkg-config --modversion libheif)"
printf 'source %q\n' "$env_file"
